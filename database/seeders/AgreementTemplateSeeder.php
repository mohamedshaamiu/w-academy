3. ދަރިވަރުން ދަމަހައްޓަންޖެހޭ ރަނުގެ ފަސް އުސޫލު

އުސޫލު 1: ކުޅެން އައުމުގެ ކުރިން އެ ދުވަހުގެ ސްކޫލު ގަޑީގައި ޓީޗަރުންގެ ފިލާވަޅުތައް ނިންމާފައި، ސްކޫލްގެ ހުރިހާ މަސައްކަތެއް ފުރިހަމަކުރުން.

