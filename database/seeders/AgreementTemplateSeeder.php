އުސޫލު 4: ކޯޗު ވާހަކަދައްކަން ފެށުމުން ހުއްޓި ހުރެ، ކޯޗަށް ބަލައި، ސަމާލުކަމާއެކު އަޑުއެހުން.

އުސޫލު 5: އަބަދުވެސް އެންމެން ދޮގެއްނުހަދާ، ބުލީއާއި މަލާމާތްނުކޮށް، ރައްޓެހިކަމާއެކު ސަޕޯޓްކޮށްދޭން ކުޅެން ކުރިއަށް ގެންދިއުން.

4. ރަނގަޅުކުރުމަށް ފިޔަވަޅުތައް އެޅުމުގެ ދެލި ތަރުތީބު

ދަރިވަރަކު ގޭގައި، ސްކޫލުގައި ނުވަތަ އެކަޑަމީގައި ގަވާއިދާ ޚިލާފުވެއްޖެނަމަ (މިސާލަކަށް: އެހެން ކުދިންނަށް އަނިޔާކުރުން، ބަސްނޭހުން، ރުޅިގަދަވެ ރުޅިވެރިކަން ދެއްކުން، ނުވަތަ ބެލެނިވެރިން/ޓީޗަރުންނަށް އިޙްތިރާމް ކުޑަކުރުން ފަދަ ޢަމަލެއް ކޮށްފިނަމަ)، ތިރީގައިވާ ފިޔަވަޅުތައް ތަރުތީބުން އެޅޭނެއެވެ:

ސްޓްރައިކް 1 — ފުރަތަމަ އިންޒާރު: ކޯޗު ކުއްޖާ ހުއްޓުވައި އަނގަބަހުން ނަސޭހަތްދޭނެއެވެ. އަދި ވިސްނާދިނުމަށްޓަކައި 3-5 މިނެޓުގެ "ޓައިމް އައުޓް" ބައިންދައްޓައި، ޕްރެކްޓިސްތެރެއިން ބޭރުގައި ބައިންދާނެއެވެ. ޕްރެކްޓިސް ނިމުމުން ކޯޗު ބެލެނިވެރިޔާއަށް މިކަން އަންގާނެއެވެ.

ސްޓްރައިކް 2 — އެންމެ ފަހުގެ އިންޒާރު: ނޭދެވޭ ސުލޫކު ތަކުރާރުވުން ނުވަތަ އާ އުސޫލަކާ ޚިލާފުވެއްޖެނަމަ، އެ ދުވަހުގެ ޕްރެކްޓިސް ސެޝަންގެ ބާކީ ބައިން ކުއްޖާ ވަކިކުރެވޭނެއެވެ. ކުއްޖާގެ ސުލޫކު އިސްލާޙުކުރާނެ ސްޓްރެޓެޖީއަކަށް މަޝްވަރާކުރުމަށް ރަސްމީ ބައްދަލުވުމެއް ނުވަތަ ކޯލެއް ކުރެވޭނެއެވެ.

ސްޓްރައިކް 3 — ސަސްޕެންޝަން: ޖުމްލަ 3 އިންޒާރު ހަމަވުމުން އެކަޑަމީން ވަގުތީ ގޮތުން ސަސްޕެންޑް ކުރެވޭނެއެވެ. މި މުއްދަތުގައި ޕްރެކްޓިސްތަކަށް ނުވަތަ މެޗުތަކަށް ނާދެވޭނެއެވެ. ގޭގައްޔާއި ސްކޫލުގައި ކުއްޖާގެ ސުލޫކު އިސްލާޙުކުރުމަށް ބެލެނިވެރިން ގޭގައި މަސައްކަތް ކުރަންޖެހޭނެއެވެ.

5. ބެލެނިވެރިޔާގެ އިޤުރާރު

މި އެކަޑަމީގައި އަޅުގަނޑުގެ ދަރިފުޅު ބައިވެރިވުމަކީ، ކުޅިވަރު ދަނޑުން ބޭރުގައި (ގޭގައްޔާއި ސްކޫލުގައި) ދަރިފުޅު ބަހައްޓާ ސުލޫކާ ސީދާ ގުޅިފައިވާ އިމްތިޔާޒެއް ކަން މި ފޯމު ބަލައިގަންނަ ހިނދު، ތިރީގައިވާ ކަންކަމަށް އެއްބަސްވަމެވެ:

ތަޢުލީމީ އިސްކަން: ދަރިވަރު ޕްރެކްޓިސްތަކަށް ދެވޭނީ ހަވާލުކުރި ސްކޫލް މަސައްކަތްތައް ފުރިހަމަކޮށް ޓީޗަރުންނަށް ކިޔަމަންތެރިވާނެކަމެވެ.

ގޭގައި އިޙްތިރާމްކުރުން: ގޭގައި މައިންބަފައިންނާއި ބެލެނިވެރިންނަށް ފުރިހަމައަށް ކިޔަމަންތެރިވާނެކަމެވެ.

